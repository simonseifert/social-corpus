def test_groq_is_the_fallback_when_the_server_is_down(monkeypatch, tmp_path):
    f = tmp_path / "x.mp4"
    f.write_bytes(b"v")
    monkeypatch.setattr(tx, "_whisper_servers", lambda: ["http://gpu:8093"])
    monkeypatch.setattr(tx, "_env_key", lambda n: "k" if n == "GROQ_API_KEY" else None)

    def post(url, *a, **k):
        if "8093" in url:
            raise tx.TranscribeError("connection refused")
        return tx.Transcript("from groq", [], "hr")
    monkeypatch.setattr(tx, "_post_whisper", post)
    assert tx.transcribe_whisper(f, language="hr").text == "from groq"


