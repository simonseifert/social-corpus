def test_an_hls_playlist_url_is_fetched_as_a_video(clip, tmp_path, monkeypatch):
    """HarvestAPI hands LinkedIn video as dms.licdn.com/playlist/... (an HLS
    playlist). Stored verbatim, the 2 KB of playlist text went to whisper, which
    answered 500, and the clip burned its attempts (harbor-ferries, 2026-10-23)."""
    import io
    url = "https://dms.licdn.com/playlist/vid/dynamic/x?e=1"
    monkeypatch.setattr(m, "_open",
                        lambda req, timeout=None: io.BytesIO(b"#EXTM3U\n#EXT-X-VERSION:7\n"))
    monkeypatch.setattr(m, "_resolve", lambda h, p: ["13.107.42.14"])
    seen = []

    def run(cmd, **kw):
        seen.append(cmd)
        Path(cmd[-1]).write_bytes(clip.read_bytes())
        return subprocess.CompletedProcess(cmd, 0, "", "")
    monkeypatch.setattr(m.subprocess, "run", run)
    out = m.download(url, tmp_path / "v.mp4")
    assert out.read_bytes() == clip.read_bytes()
    cmd = seen[0]
    assert cmd[cmd.index("-protocol_whitelist") + 1] == "https,tls,tcp,crypto"
    assert "-allowed_extensions" not in cmd
    assert cmd.index("-protocol_whitelist") < cmd.index("-i")


