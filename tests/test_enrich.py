def test_keyframes_are_evenly_spaced(clip, tmp_path):
    frames = m.keyframes(clip, tmp_path / "f", count=3)
    assert len(frames) >= 2, "expected multiple sampled frames"
    assert all(f.path.exists() and f.path.stat().st_size > 0 for f in frames)
    offsets = [f.t_offset_s for f in frames]
    assert offsets == sorted(offsets)
    assert offsets[0] == 0.0


def test_keyframes_are_downscaled(clip, tmp_path):
    frames = m.keyframes(clip, tmp_path / "f", count=2, width=160)
    out = subprocess.run(
        ["ffprobe", "-v", "error", "-select_streams", "v:0",
         "-show_entries", "stream=width", "-of", "csv=p=0", str(frames[0].path)],
        capture_output=True, text=True,
    )
    assert out.stdout.strip() == "160"


